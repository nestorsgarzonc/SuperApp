// Package accesslog records and lists gate movements (entries, exits and
// denied attempts) registered by guards. It is separate from the access
// grants (passes): a grant says who MAY enter, a log says who DID.
package accesslog

import (
	"fmt"
	"strings"
	"time"
	"unicode/utf8"

	"github.com/google/uuid"
)

const (
	MovementEntry   = "ENTRY"
	MovementExit    = "EXIT"
	MovementAttempt = "ATTEMPT"

	SubjectVisitor  = "VISITOR"
	SubjectResident = "RESIDENT"

	ResultAuthorized = "AUTHORIZED"
	ResultDenied     = "DENIED"

	RoleGuard    = "GUARD"
	RoleAdmin    = "ADMIN"
	RoleResident = "RESIDENT"

	maxTextLength = 200
	// A guard's device may be offline for a while before syncing, but a
	// timestamp far in the past or the future is a client bug or tampering.
	maxBackdate   = 7 * 24 * time.Hour
	maxFutureSkew = 5 * time.Minute

	defaultListLimit = 100
	maxListLimit     = 500
)

var validMovements = map[string]bool{MovementEntry: true, MovementExit: true, MovementAttempt: true}
var validResults = map[string]bool{ResultAuthorized: true, ResultDenied: true}

type AccessLog struct {
	ID               uuid.UUID  `json:"id"`
	ClientID         uuid.UUID  `json:"client_id"`
	ComplexID        uuid.UUID  `json:"complex_id"`
	Movement         string     `json:"movement"`
	Result           string     `json:"result"`
	SubjectType      string     `json:"subject_type"`
	SubjectUserID    uuid.UUID  `json:"-"`
	VisitorName      string     `json:"visitor_name"`
	UnitLabel        string     `json:"unit_label"`
	VisitorType      *string    `json:"visitor_type,omitempty"`
	Vehicle          *string    `json:"vehicle,omitempty"`
	GrantID          *uuid.UUID `json:"grant_id,omitempty"`
	RegisteredBy     uuid.UUID  `json:"registered_by"`
	RegisteredByName string     `json:"registered_by_name"`
	OccurredAt       time.Time  `json:"occurred_at"`
	RecordedAt       time.Time  `json:"recorded_at"`
}

// CreateRequest is one movement. ClientID is generated by the caller and makes
// the call idempotent, so an offline queue can retry safely.
type CreateRequest struct {
	ClientID    uuid.UUID  `json:"client_id"`
	Movement    string     `json:"movement"`
	Result      string     `json:"result"`
	VisitorName string     `json:"visitor_name"`
	UnitLabel   string     `json:"unit_label"`
	VisitorType *string    `json:"visitor_type,omitempty"`
	Vehicle     *string    `json:"vehicle,omitempty"`
	GrantID     *uuid.UUID `json:"grant_id,omitempty"`
	OccurredAt  *time.Time `json:"occurred_at,omitempty"`
}

func (r CreateRequest) validate(now time.Time) map[string][]string {
	errs := map[string][]string{}
	add := func(field, msg string) { errs[field] = append(errs[field], msg) }

	if r.ClientID == uuid.Nil {
		add("client_id", "required")
	}
	if !validMovements[r.Movement] {
		add("movement", "must be one of ENTRY, EXIT, ATTEMPT")
	}
	if !validResults[r.Result] {
		add("result", "must be AUTHORIZED or DENIED")
	}
	if r.Movement == MovementAttempt && r.Result == ResultAuthorized {
		add("result", "an ATTEMPT cannot be AUTHORIZED; register an ENTRY instead")
	}
	if (r.Movement == MovementEntry || r.Movement == MovementExit) && r.Result == ResultDenied {
		add("result", "an ENTRY/EXIT is always AUTHORIZED; use ATTEMPT for denied access")
	}
	if strings.TrimSpace(r.VisitorName) == "" {
		add("visitor_name", "required")
	}
	if strings.TrimSpace(r.UnitLabel) == "" {
		add("unit_label", "required")
	}
	checkLen := func(field, v string) {
		if !utf8.ValidString(v) {
			add(field, "must be valid UTF-8")
		}
		if len(v) > maxTextLength {
			add(field, fmt.Sprintf("must be at most %d characters", maxTextLength))
		}
	}
	checkLen("visitor_name", r.VisitorName)
	checkLen("unit_label", r.UnitLabel)
	if r.VisitorType != nil {
		checkLen("visitor_type", *r.VisitorType)
	}
	if r.Vehicle != nil {
		checkLen("vehicle", *r.Vehicle)
	}
	if r.OccurredAt != nil {
		if r.OccurredAt.After(now.Add(maxFutureSkew)) {
			add("occurred_at", "must not be in the future")
		}
		if r.OccurredAt.Before(now.Add(-maxBackdate)) {
			add("occurred_at", "is too old (max 7 days)")
		}
	}
	return errs
}

type ListFilter struct {
	From     *time.Time
	To       *time.Time
	Movement string
	Result   string
	Subject  string
	Limit    int
}

func (f ListFilter) validate() map[string][]string {
	errs := map[string][]string{}
	if f.Movement != "" && !validMovements[f.Movement] {
		errs["movement"] = []string{"must be one of ENTRY, EXIT, ATTEMPT"}
	}
	if f.Result != "" && !validResults[f.Result] {
		errs["result"] = []string{"must be AUTHORIZED or DENIED"}
	}
	if f.Subject != "" && f.Subject != SubjectVisitor && f.Subject != SubjectResident {
		errs["subject"] = []string{"must be VISITOR or RESIDENT"}
	}
	if f.From != nil && f.To != nil && !f.From.Before(*f.To) {
		errs["to"] = []string{"must be after from"}
	}
	return errs
}
